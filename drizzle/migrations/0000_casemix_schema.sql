CREATE INDEX patients_tanggal_idx ON public.patients (tanggal);
GRANT SELECT, INSERT, UPDATE, DELETE ON public.patients TO authenticated;
GRANT ALL ON public.patients TO service_role;
ALTER TABLE public.patients ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Team reads patients" ON public.patients FOR SELECT TO authenticated USING (true);
CREATE POLICY "Inputers add patients" ON public.patients FOR INSERT TO authenticated WITH CHECK (public.can_write(auth.uid()));
CREATE POLICY "Inputers edit patients" ON public.patients FOR UPDATE TO authenticated USING (public.can_write(auth.uid())) WITH CHECK (public.can_write(auth.uid()));
CREATE POLICY "Permitted users delete patients" ON public.patients FOR DELETE TO authenticated USING (public.has_perm(auth.uid(), 'hapus'));

-- Field-level permissions: fields the user may not input are zeroed on insert and kept on update.
CREATE OR REPLACE FUNCTION public.enforce_patient_permissions()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE uid uuid := auth.uid();
BEGIN
  NEW.updated_at := now();
  IF uid IS NULL THEN RETURN NEW; END IF;
  IF TG_OP = 'INSERT' THEN NEW.created_by := uid; ELSE NEW.created_by := OLD.created_by; END IF;
  IF NOT public.has_perm(uid, 'sdm') THEN
    IF TG_OP = 'INSERT' THEN
      NEW.jasa_dpjp := 0; NEW.jasa_du := 0; NEW.jasa_penunjang := 0; NEW.konsul := 0;
    ELSE
      NEW.jasa_dpjp := OLD.jasa_dpjp; NEW.jasa_du := OLD.jasa_du; NEW.jasa_penunjang := OLD.jasa_penunjang; NEW.konsul := OLD.konsul;
    END IF;
  END IF;
  IF NOT public.has_perm(uid, 'ops') THEN
    IF TG_OP = 'INSERT' THEN
      NEW.farmasi := 0; NEW.lab := 0; NEW.radiologi := 0; NEW.darah := 0; NEW.pa := 0; NEW.ops_lain := 0;
    ELSE
      NEW.farmasi := OLD.farmasi; NEW.lab := OLD.lab; NEW.radiologi := OLD.radiologi; NEW.darah := OLD.darah; NEW.pa := OLD.pa; NEW.ops_lain := OLD.ops_lain;
    END IF;
  END IF;
  IF NOT public.has_perm(uid, 'billing') THEN
    IF TG_OP = 'INSERT' THEN NEW.billing := 0; ELSE NEW.billing := OLD.billing; END IF;
  END IF;
  RETURN NEW;
END $$;

