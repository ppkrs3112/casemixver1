CREATE TABLE public.patients (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  tanggal date NOT NULL,
  nama text NOT NULL,
  rm text NOT NULL DEFAULT '',
  dpjp text NOT NULL DEFAULT '',
  inacbgs numeric(16,2) NOT NULL DEFAULT 0,
  billing numeric(16,2) NOT NULL DEFAULT 0,
  jasa_dpjp numeric(16,2) NOT NULL DEFAULT 0,
  jasa_du numeric(16,2) NOT NULL DEFAULT 0,
  jasa_penunjang numeric(16,2) NOT NULL DEFAULT 0,
  konsul numeric(16,2) NOT NULL DEFAULT 0,
  farmasi numeric(16,2) NOT NULL DEFAULT 0,
  lab numeric(16,2) NOT NULL DEFAULT 0,
  radiologi numeric(16,2) NOT NULL DEFAULT 0,
  darah numeric(16,2) NOT NULL DEFAULT 0,
  pa numeric(16,2) NOT NULL DEFAULT 0,
  ops_lain numeric(16,2) NOT NULL DEFAULT 0,
  created_by uuid,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
